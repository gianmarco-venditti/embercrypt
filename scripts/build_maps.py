#!/usr/bin/env python3
"""Generate the two small hand-designed Flare maps, without third-party dependencies."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
MAPS = ROOT / 'mods' / 'ember_slice' / 'maps'
WIDTH, HEIGHT = 40, 30
START = (6, 24)
CHEST = (18, 14)
EXIT = (34, 3)
ENEMIES = [
    ('ember_melee', 16, 20), ('ember_melee', 21, 19),
    ('ember_archer', 22, 14), ('ember_melee', 29, 11),
    ('ember_melee', 33, 10), ('ember_archer', 35, 7),
    ('ember_guardian', 32, 5),
]


def rectangle(floor, x1, y1, x2, y2):
    floor.update((x, y) for y in range(y1, y2 + 1) for x in range(x1, x2 + 1))


def crypt_floor():
    floor = set()
    for bounds in [(3, 19, 10, 26), (14, 13, 23, 22), (27, 3, 36, 12),
                   (10, 20, 14, 22), (22, 11, 28, 14)]:
        rectangle(floor, *bounds)
    return floor


def layer(name, grid):
    return f'[layer]\ntype={name}\nformat=dec\ndata=\n' + ',\n'.join(
        ','.join(map(str, row)) for row in grid) + '\n\n'


def event(**values):
    return '[event]\n' + '\n'.join(f'{k}={v}' for k, v in values.items()) + '\n\n'


def terrain(title, floor, start, width=WIDTH, height=HEIGHT, chest=False):
    background = [[0] * width for _ in range(height)]
    objects = [[0] * width for _ in range(height)]
    collision = [[1] * width for _ in range(height)]
    for x, y in floor:
        background[y][x] = 16 + ((x * 7 + y * 3) % 4)
        collision[y][x] = 0
    # Back walls only: keep the playable floor visible in the isometric view.
    for y in range(1, height - 1):
        for x in range(1, width - 1):
            if (x, y) in floor:
                continue
            if (x, y + 1) in floor and (x + 1, y) in floor:
                objects[y][x] = 48
            elif (x, y + 1) in floor:
                objects[y][x] = 49
            elif (x + 1, y) in floor:
                objects[y][x] = 50
    if chest:
        objects[CHEST[1]][CHEST[0]] = 144
        background[EXIT[1]][EXIT[0]] = 60
        for x, y in [(4, 20), (15, 14), (28, 4)]:
            objects[y][x] = 167
    return (f'# Generated by scripts/build_maps.py. Edit the generator, then rebuild.\n'
            f'[header]\nwidth={width}\nheight={height}\n'
            f'title={title}\nhero_pos={start[0]},{start[1]}\n'
            'orientation=isometric\ntilewidth=192\ntileheight=96\n'
            'background_color=8,7,12,255\nfogofwar=1\n'
            'tileset=tilesetdefs/tileset_dungeon.txt\n'
            'music=music/wind_ambient.ogg\n\n'
            + layer('background', background) + layer('object', objects)
            + layer('collision', collision))


def crypt():
    text = terrain('La Cripta della Brace', crypt_floor(), START, chest=True)
    text += event(activate='on_load', location='6,24,1,1',
                  requires_not_status='ember_started', set_status='ember_started',
                  msg='La Brace si spegne. Sconfiggi il Guardiano e raggiungi l\'uscita nella sua sala. Clic sinistro: muovi/attacca. Destro: abilita. I: inventario. L: obiettivo.',
                  save_game='true', repeat='false')
    text += event(activate='on_trigger', location='12,20,1,3',
                  requires_not_status='ember_warning', set_status='ember_warning',
                  msg='Le prime sentinelle. Affrontale una alla volta; usa le pozioni nella barra in basso.', repeat='false')
    text += event(activate='on_interact', location='18,14,1,1', hotspot='location',
                  tooltip='Forziere delle braci', requires_not_status='ember_chest',
                  reward_item='5000:1,2:2', set_status='ember_chest',
                  mapmod='object,18,14,160',
                  msg='Hai trovato la Lama della Brace e due pozioni. Apri l\'inventario (I) per equipaggiarla.',
                  soundfx='soundfx/wood_open.ogg', repeat='false')
    text += event(activate='on_load', location='18,14,1,1',
                  requires_status='ember_chest', mapmod='object,18,14,160')
    text += event(activate='on_trigger', location='27,11,2,2',
                  requires_not_status='ember_boss_warning', set_status='ember_boss_warning',
                  msg='Il Guardiano e nella sala in fondo. La runa luminosa alle sue spalle indica l\'uscita.', repeat='false')
    for category, x, y in ENEMIES:
        text += ('[enemy]\n' + f'category={category}\nlevel=1\nnumber=1\n'
                 f'location={x},{y},1,1\nwander_radius=0\n')
        if category == 'ember_guardian':
            text += 'requires_not_status=ember_guardian_dead\n'
        text += '\n'
    text += event(activate='static', location='34,3,1,1',
                  requires_status='ember_guardian_dead', requires_not_status='ember_boss_reward',
                  set_status='ember_boss_reward', reward_currency='25',
                  msg='Il Guardiano e caduto! Recupera la Brace: raggiungi la runa luminosa in fondo alla sala.', repeat='false')
    text += event(activate='on_trigger', location='34,3,2,1', hotspot='location',
                  tooltip='Uscita — porta la Brace al sicuro', requires_status='ember_guardian_dead',
                  intermap='maps/ember_refuge.txt,5,5', show_on_minimap='true')
    text += event(activate='on_trigger', location='34,3,2,1',
                  requires_not_status='ember_guardian_dead,ember_exit_warned',
                  set_status='ember_exit_warned',
                  msg='Il Guardiano trattiene la Brace. Devi sconfiggerlo prima di uscire.', repeat='false')
    return text


def refuge():
    floor = set()
    rectangle(floor, 2, 2, 8, 8)
    text = terrain('La Brace e salva', floor, (5, 5), width=12, height=12)
    text += event(activate='on_load', location='5,5,1,1',
                  requires_not_status='ember_finished', set_status='ember_finished',
                  restore='all', save_game='true', cutscene='cutscenes/ember_victory.txt',
                  repeat='false')
    text += event(activate='on_load', location='5,5,1,1', requires_status='ember_finished',
                  msg='Avventura completata. Esc per il menu; scegli Nuova partita per riprovare.')
    return text


def build(check=False):
    for filename, content in [('ember_crypt.txt', crypt()), ('ember_refuge.txt', refuge())]:
        content = content.rstrip() + '\n'
        path = MAPS / filename
        if check:
            if not path.is_file() or path.read_text() != content:
                raise RuntimeError(f'Mappa non aggiornata: {path}. Esegui python3 scripts/build_maps.py')
        else:
            path.write_text(content)
    print('Mappe aggiornate.' if not check else 'Mappe coerenti con il generatore.')


if __name__ == '__main__':
    build(check='--check' in sys.argv)
